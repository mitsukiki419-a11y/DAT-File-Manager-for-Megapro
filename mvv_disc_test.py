"""Disc-level test of the music-video feature: add (with conversion), delete, save ISO and folder, re-read."""
import sys, os, shutil, subprocess; sys.path.insert(0, '/home/claude')
import songdisc, isoread
S = sys.argv[1]; src = sys.argv[2] if len(sys.argv) > 2 else '/home/claude/test_mppv45.iso'
ok = []; bad = []
def chk(n, c, x=''): (ok if c else bad).append(n); print(('PASS ' if c else 'FAIL ') + n + ('' if c else '  ' + str(x)[:300]), flush=True)
d = songdisc.KaraokeDisc(src)
L = d.listing(only='mv', n=500)
chk('lists the disc music videos', L['total'] == 153 and L['has_mvv'], L['total'])
chk('MV entries carry their file', d.find(90034).mvv == '90034.mvv' and d.find(90034).mvv_size == 18552298)
chk('compat check: disc file', songdisc.mvv_compatible is not None)
s = d.add_mvv(99501, S + '/clip.mp4', 'Test Video', 'Tester', workdir=S)
chk('mp4 converted', s.converted and songdisc.mvv_compatible(s.mvv_src), s.mvv_src)
info = songdisc.avi_info(open(s.mvv_src, 'rb').read(65536))
chk('converted format DX50/MP3 <=720x480', info[0] == b'DX50' and info[1] == 0x55 and info[2] <= 720 and info[3] <= 480, info)
s2 = d.add_mvv(99502, s.mvv_src, 'As Is', '', workdir=S)
chk('compatible AVI added as is', not s2.converted and s2.mvv_src == s.mvv_src)
try: d.add_mvv(90034, s.mvv_src); chk('duplicate refused', False)
except ValueError: chk('duplicate refused', True)
d.delete(90232)
out = S + '/mv_out.iso'
if os.path.exists(out): os.remove(out)
d.save(out)
iso = isoread.Disc(out)
names = {e['name'].lower(): e['size'] for e in iso.listdir('/KARA125/MVV')}
chk('new .mvv files in the ISO', names.get('99501.mvv') == os.path.getsize(s.mvv_src) and '99502.mvv' in names, sorted(names)[-4:])
chk('deleted MV file removed', '90232.mvv' not in names and '90034.mvv' in names)
chk('MVV count', len(names) == 154 + 2 - 1, len(names))
a = iso.read('/KARA125/MVV/99501.mvv'); chk('new file content intact', a == open(s.mvv_src, 'rb').read())
b = iso.read('/KARA125/MVV/90261.mvv', 0, 4096); c = isoread.Disc(src).read('/KARA125/MVV/90261.mvv', 0, 4096)
chk('old files intact', b == c)
iso.close()
# independent check (Joliet + ISO9660 + path tables) with 7z / isoinfo if available
for tool in (['isoinfo', '-J', '-f', '-i', out], ['isoinfo', '-f', '-i', out]):
    if shutil.which(tool[0]):
        r = subprocess.run(tool, capture_output=True, text=True)
        chk('isoinfo %s lists 99501' % ('Joliet' if '-J' in tool else 'ISO9660'), '99501' in r.stdout.upper() and '90232' not in r.stdout.upper(), r.stderr[-200:])
d2 = songdisc.KaraokeDisc(out)
m = d2.find(99501)
chk('re-read: entry is an MV with its file', m and m.is_mv and m.mvv and m.mvv.lower() == '99501.mvv' and m.title == 'Test Video', m and m.as_dict())
chk('re-read: deleted MV gone', d2.find(90232) is None and d2.find(90034) is not None)
chk('re-read: songs unchanged', len([x for x in d2.songs if not x.is_mv]) == len([x for x in d.songs if not x.is_mv]))
x = d2.extract(m, S + '/mvx')
chk('extract MV gives the .avi', any(p.endswith('.avi') for p in x), x)
chk('extracted video is the file', open([p for p in x if p.endswith('.avi')][0], 'rb').read() == open(s.mvv_src, 'rb').read())
d2.close()
fo = S + '/mv_folder'
shutil.rmtree(fo, ignore_errors=True)
d3 = songdisc.KaraokeDisc(src); d3.add_mvv(99503, s.mvv_src, 'Folder', ''); d3.delete(90261); d3.save(fo)
chk('folder output', os.path.exists(fo + '/KARA125/MVV/99503.mvv') and not os.path.exists(fo + '/KARA125/MVV/90261.mvv'))
print('%d passed, %d failed' % (len(ok), len(bad)), bad)
# ---- lyrics (v1.4)
import mvlyrics, karamidi
d = songdisc.KaraokeDisc(src)
lm = mvlyrics.build(d.midi(d.find(1)), 'Lyric Video', 'Tester', offset=1.5)
chk('lyrics MIDI built', karamidi.midi_ok(lm) and mvlyrics.info(lm)['syllables'] == 164 and mvlyrics.info(lm)['notes'] == 0)
s = d.add_mvv(99504, S + '/99501.mvv', 'Lyric Video', 'Tester', lyrics=lm)
chk('added MV has lyrics', s.lyr and s.as_dict()['lyrics'])
d.set_lyrics(90034, lm); d.set_lyrics(90261, lm); d.set_lyrics(90261, None)
chk('pending lyric changes', d.pending()['lyrics'] == 2, d.pending())
out = S + '/mv_lyr2.iso'
if os.path.exists(out): os.remove(out)
d.save(out)
d2 = songdisc.KaraokeDisc(out)
a, b, c = d2.find(99504), d2.find(90034), d2.find(90261)
chk('re-read: lyrics on the new MV', a.lyr and d2.midi(a) == lm)
chk('re-read: lyrics on a disc MV (record moved to the new bank)', b.lyr and b.bank == len(d2.bank_files) - 1 and d2.midi(b) == lm, (b.bank, b.offset))
chk('re-read: removed lyrics = blank record', not c.lyr and d2.src.read(d2.bank_files[c.bank][0], c.offset, 2048) == bytes(2048) and c.mvv == '90261.mvv' and c.bank == len(d2.bank_files) - 1)
chk('re-read: video files kept', b.mvv == '90034.mvv' and a.mvv.lower() == '99504.mvv')
x = d2.extract(b, S + '/mvx3')
chk('extract MV with lyrics gives .avi + lyrics .mid', any(p.endswith('.avi') for p in x) and any(p.endswith('lyrics.mid') for p in x), x)
print('%d passed, %d failed' % (len(ok), len(bad)), bad)
